"""Eight-row FP32 pre-mix oracle; no production selector."""
import triton
import triton.language as tl

@triton.jit
def premix8(x, fn, partials, out, M, EPS: tl.constexpr = 1e-6):
    row = tl.program_id(1) * 8
    n = tl.program_id(0) + tl.arange(0, 1)
    acc0 = tl.zeros((1,), tl.float32)
    acc1 = tl.zeros((1,), tl.float32)
    acc2 = tl.zeros((1,), tl.float32)
    acc3 = tl.zeros((1,), tl.float32)
    acc4 = tl.zeros((1,), tl.float32)
    acc5 = tl.zeros((1,), tl.float32)
    acc6 = tl.zeros((1,), tl.float32)
    acc7 = tl.zeros((1,), tl.float32)
    for start in tl.static_range(0, 16384, 1024):
        k = start + tl.arange(0, 1024)
        w = tl.load(fn + n[:, None] * 16384 + k[None, :], mask=n[:, None] < 24, other=0.)
        a0 = tl.load(x + (row + 0) * 16384 + k, mask=row + 0 < M, other=0.).to(tl.float32)
        acc0 += tl.sum(w * a0[None, :], axis=1)
        a1 = tl.load(x + (row + 1) * 16384 + k, mask=row + 1 < M, other=0.).to(tl.float32)
        acc1 += tl.sum(w * a1[None, :], axis=1)
        a2 = tl.load(x + (row + 2) * 16384 + k, mask=row + 2 < M, other=0.).to(tl.float32)
        acc2 += tl.sum(w * a2[None, :], axis=1)
        a3 = tl.load(x + (row + 3) * 16384 + k, mask=row + 3 < M, other=0.).to(tl.float32)
        acc3 += tl.sum(w * a3[None, :], axis=1)
        a4 = tl.load(x + (row + 4) * 16384 + k, mask=row + 4 < M, other=0.).to(tl.float32)
        acc4 += tl.sum(w * a4[None, :], axis=1)
        a5 = tl.load(x + (row + 5) * 16384 + k, mask=row + 5 < M, other=0.).to(tl.float32)
        acc5 += tl.sum(w * a5[None, :], axis=1)
        a6 = tl.load(x + (row + 6) * 16384 + k, mask=row + 6 < M, other=0.).to(tl.float32)
        acc6 += tl.sum(w * a6[None, :], axis=1)
        a7 = tl.load(x + (row + 7) * 16384 + k, mask=row + 7 < M, other=0.).to(tl.float32)
        acc7 += tl.sum(w * a7[None, :], axis=1)
    p = tl.arange(0, 64)
    sq0 = tl.sum(tl.load(partials + (row + 0) * 64 + p, mask=row + 0 < M, other=0.), axis=0)
    tl.store(out + (row + 0) * 24 + n, acc0 * tl.rsqrt(sq0 / 16384 + EPS), mask=(n < 24) & (row + 0 < M))
    sq1 = tl.sum(tl.load(partials + (row + 1) * 64 + p, mask=row + 1 < M, other=0.), axis=0)
    tl.store(out + (row + 1) * 24 + n, acc1 * tl.rsqrt(sq1 / 16384 + EPS), mask=(n < 24) & (row + 1 < M))
    sq2 = tl.sum(tl.load(partials + (row + 2) * 64 + p, mask=row + 2 < M, other=0.), axis=0)
    tl.store(out + (row + 2) * 24 + n, acc2 * tl.rsqrt(sq2 / 16384 + EPS), mask=(n < 24) & (row + 2 < M))
    sq3 = tl.sum(tl.load(partials + (row + 3) * 64 + p, mask=row + 3 < M, other=0.), axis=0)
    tl.store(out + (row + 3) * 24 + n, acc3 * tl.rsqrt(sq3 / 16384 + EPS), mask=(n < 24) & (row + 3 < M))
    sq4 = tl.sum(tl.load(partials + (row + 4) * 64 + p, mask=row + 4 < M, other=0.), axis=0)
    tl.store(out + (row + 4) * 24 + n, acc4 * tl.rsqrt(sq4 / 16384 + EPS), mask=(n < 24) & (row + 4 < M))
    sq5 = tl.sum(tl.load(partials + (row + 5) * 64 + p, mask=row + 5 < M, other=0.), axis=0)
    tl.store(out + (row + 5) * 24 + n, acc5 * tl.rsqrt(sq5 / 16384 + EPS), mask=(n < 24) & (row + 5 < M))
    sq6 = tl.sum(tl.load(partials + (row + 6) * 64 + p, mask=row + 6 < M, other=0.), axis=0)
    tl.store(out + (row + 6) * 24 + n, acc6 * tl.rsqrt(sq6 / 16384 + EPS), mask=(n < 24) & (row + 6 < M))
    sq7 = tl.sum(tl.load(partials + (row + 7) * 64 + p, mask=row + 7 < M, other=0.), axis=0)
    tl.store(out + (row + 7) * 24 + n, acc7 * tl.rsqrt(sq7 / 16384 + EPS), mask=(n < 24) & (row + 7 < M))
