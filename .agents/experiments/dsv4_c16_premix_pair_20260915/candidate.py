"""Pending two independent output columns, eight rows; no production selector."""
import triton
import triton.language as tl

@triton.jit
def premix8_pair(x, fn, partials, out, M, EPS: tl.constexpr = 1e-6):
    row = tl.program_id(1) * 8
    n0 = tl.program_id(0) * 2 + tl.arange(0, 1)
    n1 = n0 + 1
    acc0a = tl.zeros((1,), tl.float32)
    acc0b = tl.zeros((1,), tl.float32)
    acc1a = tl.zeros((1,), tl.float32)
    acc1b = tl.zeros((1,), tl.float32)
    acc2a = tl.zeros((1,), tl.float32)
    acc2b = tl.zeros((1,), tl.float32)
    acc3a = tl.zeros((1,), tl.float32)
    acc3b = tl.zeros((1,), tl.float32)
    acc4a = tl.zeros((1,), tl.float32)
    acc4b = tl.zeros((1,), tl.float32)
    acc5a = tl.zeros((1,), tl.float32)
    acc5b = tl.zeros((1,), tl.float32)
    acc6a = tl.zeros((1,), tl.float32)
    acc6b = tl.zeros((1,), tl.float32)
    acc7a = tl.zeros((1,), tl.float32)
    acc7b = tl.zeros((1,), tl.float32)
    for start in tl.static_range(0, 16384, 1024):
        k = start + tl.arange(0, 1024)
        # Keep both reductions at shape[1,1024], not BLOCK_N=2.
        w0 = tl.load(fn + n0[:, None] * 16384 + k[None, :])
        w1 = tl.load(fn + n1[:, None] * 16384 + k[None, :])
        a0 = tl.load(x + (row + 0) * 16384 + k, mask=row + 0 < M, other=0.).to(tl.float32)
        acc0a += tl.sum(w0 * a0[None, :], axis=1)
        acc0b += tl.sum(w1 * a0[None, :], axis=1)
        a1 = tl.load(x + (row + 1) * 16384 + k, mask=row + 1 < M, other=0.).to(tl.float32)
        acc1a += tl.sum(w0 * a1[None, :], axis=1)
        acc1b += tl.sum(w1 * a1[None, :], axis=1)
        a2 = tl.load(x + (row + 2) * 16384 + k, mask=row + 2 < M, other=0.).to(tl.float32)
        acc2a += tl.sum(w0 * a2[None, :], axis=1)
        acc2b += tl.sum(w1 * a2[None, :], axis=1)
        a3 = tl.load(x + (row + 3) * 16384 + k, mask=row + 3 < M, other=0.).to(tl.float32)
        acc3a += tl.sum(w0 * a3[None, :], axis=1)
        acc3b += tl.sum(w1 * a3[None, :], axis=1)
        a4 = tl.load(x + (row + 4) * 16384 + k, mask=row + 4 < M, other=0.).to(tl.float32)
        acc4a += tl.sum(w0 * a4[None, :], axis=1)
        acc4b += tl.sum(w1 * a4[None, :], axis=1)
        a5 = tl.load(x + (row + 5) * 16384 + k, mask=row + 5 < M, other=0.).to(tl.float32)
        acc5a += tl.sum(w0 * a5[None, :], axis=1)
        acc5b += tl.sum(w1 * a5[None, :], axis=1)
        a6 = tl.load(x + (row + 6) * 16384 + k, mask=row + 6 < M, other=0.).to(tl.float32)
        acc6a += tl.sum(w0 * a6[None, :], axis=1)
        acc6b += tl.sum(w1 * a6[None, :], axis=1)
        a7 = tl.load(x + (row + 7) * 16384 + k, mask=row + 7 < M, other=0.).to(tl.float32)
        acc7a += tl.sum(w0 * a7[None, :], axis=1)
        acc7b += tl.sum(w1 * a7[None, :], axis=1)
    p = tl.arange(0, 64)
    sq0 = tl.sum(tl.load(partials + (row + 0) * 64 + p, mask=row + 0 < M, other=0.), axis=0)
    inv0 = tl.rsqrt(sq0 / 16384 + EPS)
    tl.store(out + (row + 0) * 24 + n0, acc0a * inv0, mask=row + 0 < M)
    tl.store(out + (row + 0) * 24 + n1, acc0b * inv0, mask=row + 0 < M)
    sq1 = tl.sum(tl.load(partials + (row + 1) * 64 + p, mask=row + 1 < M, other=0.), axis=0)
    inv1 = tl.rsqrt(sq1 / 16384 + EPS)
    tl.store(out + (row + 1) * 24 + n0, acc1a * inv1, mask=row + 1 < M)
    tl.store(out + (row + 1) * 24 + n1, acc1b * inv1, mask=row + 1 < M)
    sq2 = tl.sum(tl.load(partials + (row + 2) * 64 + p, mask=row + 2 < M, other=0.), axis=0)
    inv2 = tl.rsqrt(sq2 / 16384 + EPS)
    tl.store(out + (row + 2) * 24 + n0, acc2a * inv2, mask=row + 2 < M)
    tl.store(out + (row + 2) * 24 + n1, acc2b * inv2, mask=row + 2 < M)
    sq3 = tl.sum(tl.load(partials + (row + 3) * 64 + p, mask=row + 3 < M, other=0.), axis=0)
    inv3 = tl.rsqrt(sq3 / 16384 + EPS)
    tl.store(out + (row + 3) * 24 + n0, acc3a * inv3, mask=row + 3 < M)
    tl.store(out + (row + 3) * 24 + n1, acc3b * inv3, mask=row + 3 < M)
    sq4 = tl.sum(tl.load(partials + (row + 4) * 64 + p, mask=row + 4 < M, other=0.), axis=0)
    inv4 = tl.rsqrt(sq4 / 16384 + EPS)
    tl.store(out + (row + 4) * 24 + n0, acc4a * inv4, mask=row + 4 < M)
    tl.store(out + (row + 4) * 24 + n1, acc4b * inv4, mask=row + 4 < M)
    sq5 = tl.sum(tl.load(partials + (row + 5) * 64 + p, mask=row + 5 < M, other=0.), axis=0)
    inv5 = tl.rsqrt(sq5 / 16384 + EPS)
    tl.store(out + (row + 5) * 24 + n0, acc5a * inv5, mask=row + 5 < M)
    tl.store(out + (row + 5) * 24 + n1, acc5b * inv5, mask=row + 5 < M)
    sq6 = tl.sum(tl.load(partials + (row + 6) * 64 + p, mask=row + 6 < M, other=0.), axis=0)
    inv6 = tl.rsqrt(sq6 / 16384 + EPS)
    tl.store(out + (row + 6) * 24 + n0, acc6a * inv6, mask=row + 6 < M)
    tl.store(out + (row + 6) * 24 + n1, acc6b * inv6, mask=row + 6 < M)
    sq7 = tl.sum(tl.load(partials + (row + 7) * 64 + p, mask=row + 7 < M, other=0.), axis=0)
    inv7 = tl.rsqrt(sq7 / 16384 + EPS)
    tl.store(out + (row + 7) * 24 + n0, acc7a * inv7, mask=row + 7 < M)
    tl.store(out + (row + 7) * 24 + n1, acc7b * inv7, mask=row + 7 < M)
