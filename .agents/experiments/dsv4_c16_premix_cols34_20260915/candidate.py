    inv1 = tl.rsqrt(sq1 / 16384 + EPS)
    tl.store(out + (row + 1) * 24 + n0, acc1_0 * inv1, mask=row + 1 < M)
    tl.store(out + (row + 1) * 24 + n1, acc1_1 * inv1, mask=row + 1 < M)
    tl.store(out + (row + 1) * 24 + n2, acc1_2 * inv1, mask=row + 1 < M)
    sq2 = tl.sum(tl.load(partials + (row + 2) * 64 + p, mask=row + 2 < M, other=0.), axis=0)
    inv2 = tl.rsqrt(sq2 / 16384 + EPS)
    tl.store(out + (row + 2) * 24 + n0, acc2_0 * inv2, mask=row + 2 < M)
    tl.store(out + (row + 2) * 24 + n1, acc2_1 * inv2, mask=row + 2 < M)
