        acc3_2 += tl.sum(w2 * a3[None, :], axis=1)
        a4 = tl.load(x + (row + 4) * 16384 + k, mask=row + 4 < M, other=0.).to(tl.float32)
        acc4_0 += tl.sum(w0 * a4[None, :], axis=1)
        acc4_1 += tl.sum(w1 * a4[None, :], axis=1)
        acc4_2 += tl.sum(w2 * a4[None, :], axis=1)
        a5 = tl.load(x + (row + 5) * 16384 + k, mask=row + 5 < M, other=0.).to(tl.float32)
        acc5_0 += tl.sum(w0 * a5[None, :], axis=1)
        acc5_1 += tl.sum(w1 * a5[None, :], axis=1)
        acc5_2 += tl.sum(w2 * a5[None, :], axis=1)
