    acc6_1 = tl.zeros((1,), tl.float32)
    acc6_2 = tl.zeros((1,), tl.float32)
    acc7_0 = tl.zeros((1,), tl.float32)
    acc7_1 = tl.zeros((1,), tl.float32)
    acc7_2 = tl.zeros((1,), tl.float32)
    for start in tl.static_range(0, 16384, 1024):
        k = start + tl.arange(0, 1024)
        w0 = tl.load(fn + n0[:, None] * 16384 + k[None, :])
        w1 = tl.load(fn + n1[:, None] * 16384 + k[None, :])
        w2 = tl.load(fn + n2[:, None] * 16384 + k[None, :])
        a0 = tl.load(x + (row + 0) * 16384 + k, mask=row + 0 < M, other=0.).to(tl.float32)
        acc0_0 += tl.sum(w0 * a0[None, :], axis=1)
        acc0_1 += tl.sum(w1 * a0[None, :], axis=1)
        acc0_2 += tl.sum(w2 * a0[None, :], axis=1)
        a1 = tl.load(x + (row + 1) * 16384 + k, mask=row + 1 < M, other=0.).to(tl.float32)
